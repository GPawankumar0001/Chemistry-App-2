def metric_card(label: str, value: str, note: str = "") -> str:
    return (
        '<div class="metric-card">'
        f'<div class="metric-label">{html.escape(label)}</div>'
        f'<div class="metric-value">{html.escape(value)}</div>'
        f'<div class="metric-note">{html.escape(note)}</div>'
        '</div>'
    )

def show_3d_viewer(molblock: str, height: int = 520) -> None:
    """Render a self-contained py3Dmol-style viewer using a stable HTML component."""
    # Mol block is generated by RDKit/PubChem, not user-provided HTML.
    safe_block = json.dumps(molblock)
    viewer_html = f"""
    <!doctype html><html><head><meta charset="utf-8">
    <style>
      html,body{{margin:0;padding:0;background:#08111f;color:#dcecff;font-family:Arial,sans-serif;}}
      #viewer{{width:100%;height:{height}px;position:relative;border:1px solid rgba(64,220,255,.25);border-radius:16px;overflow:hidden;}}
      #hint{{position:absolute;left:14px;bottom:10px;z-index:2;font-size:11px;color:#8aa6c6;pointer-events:none;}}
      #fallback{{padding:18px;color:#ffcf80;}}
    </style>
    <script src="https://3Dmol.org/build/3Dmol-min.js"></script></head>
    <body><div id="viewer"><div id="hint">Drag to rotate · Scroll to zoom · Right-drag to pan</div></div>
    <script>
      const molData = {safe_block};
      function bootViewer(){{
        const el = document.getElementById("viewer");
        if (!window.$3Dmol) {{
          el.innerHTML = '<div id="fallback">3D viewer library could not load. Check your network connection and reload.</div>';
          return;
        }}
        try {{
          const viewer = $3Dmol.createViewer(el, {{backgroundColor:"#08111f", antialias:true}});
          viewer.addModel(molData, "sdf");
          viewer.setStyle({{}}, {{stick:{{radius:0.16, colorscheme:"Jmol"}}, sphere:{{scale:0.23, colorscheme:"Jmol"}}}});
          viewer.zoomTo();
          viewer.zoom(0.86);
          viewer.render();
          window.addEventListener("resize", () => viewer.resize(), {{passive:true}});
        }} catch(err) {{
          el.innerHTML = '<div id="fallback">Unable to render this structure: ' + String(err) + '</div>';
        }}
      }}
      if (document.readyState === "complete") bootViewer();
      else window.addEventListener("load", bootViewer, {{once:true}});
    </script></body></html>
    """
    components.html(viewer_html, height=height + 8, scrolling=False)

if page == "Molecule Explorer":
    st.markdown('<div class="section-heading"><span class="eyebrow">01 / DISCOVER</span><h2>Molecule Explorer</h2><p>Search by compound name, PubChem CID or paste a SMILES notation.</p></div>', unsafe_allow_html=True)

    c1, c2 = st.columns([3, 1])
    with c1:
        query = st.text_input(
            "COMPOUND / CID / SMILES",
            placeholder="Try caffeine, aspirin, glucose or a SMILES string",
            help="Enter a compound name, numeric PubChem CID, or SMILES notation.",
        )
    with c2:
        st.markdown("<div style='height:28px'></div>", unsafe_allow_html=True)
        search_clicked = st.button("⟶  ANALYZE MOLECULE", use_container_width=True, type="primary")

    if search_clicked:
        if not query.strip():
            st.error("Enter a compound name, CID or SMILES string.")
        else:
            with st.spinner("Resolving molecular identity and calculating descriptors…"):
                try:
                    compound = fetch_pubchem_compound(query.strip())
                    smiles = compound.get("canonical_smiles") or compound.get("isomeric_smiles")
                    if not smiles:
                        raise PubChemError("PubChem did not return a usable SMILES string.")
                    valid, message = validate_smiles(smiles)
                    if not valid:
                        raise PubChemError(message)
                    descriptors = calculate_descriptors(smiles)
                    molblock = generate_3d_structure(smiles, compound.get("cid"))
                    st.session_state.compound = compound
                    st.session_state.descriptors = descriptors
                    st.session_state.molblock = molblock
                    st.session_state.safety_sections = []
                except Exception as exc:
                    st.error(f"Analysis could not be completed: {exc}")

    compound = st.session_state.compound
    desc = st.session_state.descriptors
    if compound and desc:
        st.markdown(
            f'<div class="compound-banner"><div><div class="eyebrow">IDENTIFIED COMPOUND · CID {html.escape(str(compound.get("cid","—")))}</div>'
            f'<h3>{html.escape(compound.get("name") or "Unnamed compound")}</h3>'
            f'<p>{html.escape(compound.get("molecular_formula") or "Formula unavailable")} · {html.escape(compound.get("iupac_name") or "IUPAC name unavailable")}</p></div>'
            '<div class="compound-chip">IDENTITY RESOLVED</div></div>',
            unsafe_allow_html=True,
        )

        m1, m2, m3, m4 = st.columns(4)
        for col, label, key, suffix in [
            (m1, "Molecular weight", "MolecularWeight", "g/mol"),
            (m2, "XLogP3", "XLogP", ""),
            (m3, "TPSA", "TPSA", "Å²"),
            (m4, "Rotatable bonds", "RotatableBonds", ""),
        ]:
            value = desc.get(key)
            with col:
                st.markdown(metric_card(label, "—" if value is None else f"{value} {suffix}", "RDKit calculated"), unsafe_allow_html=True)

        left, right = st.columns([1.1, 1])
        with left:
            st.markdown('<div class="panel-title">MOLECULAR STRUCTURE</div>', unsafe_allow_html=True)
            if st.session_state.molblock:
                show_3d_viewer(st.session_state.molblock)
            else:
                st.info("3D coordinates could not be generated for this structure.")
            st.caption("Interactive 3D rendering. Structure geometry is computationally generated and should be treated as a model.")
        with right:
            st.markdown('<div class="panel-title">PHYSICOCHEMICAL PROFILE</div>', unsafe_allow_html=True)
            st.dataframe(render_descriptor_table(desc), use_container_width=True, hide_index=True)
            st.markdown(f'<div class="info-strip">{html.escape(classify_lipinski(desc))}</div>', unsafe_allow_html=True)

        with st.expander("Molecular identifiers and source record", expanded=False):
            st.write("**Canonical SMILES**")
            st.code(compound.get("canonical_smiles") or "Not available")
            st.write("**Isomeric SMILES**")
            st.code(compound.get("isomeric_smiles") or "Not available")
            st.write("**PubChem record**")
            st.link_button("Open compound in PubChem", f"https://pubchem.ncbi.nlm.nih.gov/compound/{compound.get('cid')}", use_container_width=False)

    else:
        st.markdown(
            '<div class="empty-state"><div class="empty-icon">⌬</div><h3>Your molecular workspace is ready</h3>'
            '<p>Enter a molecule above to unlock its structure, calculated descriptors and scientific record.</p></div>',
            unsafe_allow_html=True,
        )

elif page == "ADME & Safety":
    st.markdown('<div class="section-heading"><span class="eyebrow">02 / PROFILE</span><h2>ADME & Safety Intelligence</h2><p>Explore calculated molecular descriptors and source-linked safety evidence.</p></div>', unsafe_allow_html=True)
    compound = st.session_state.compound
    desc = st.session_state.descriptors
    if not compound or not desc:
        st.info("Analyze a compound in Molecule Explorer first.")
    else:
        st.markdown("#### ADME-relevant physicochemical descriptors")
        st.caption("These are structure-derived descriptors and screening indicators, not measured pharmacokinetic values.")
        cols = st.columns(4)
        adme_cards = [
            ("Lipophilicity", desc.get("XLogP"), "LogP · partitioning proxy"),
            ("Polar surface", desc.get("TPSA"), "Å² · polarity proxy"),
            ("H-bond donors", desc.get("NumHDonors"), "Hydrogen-bond donor count"),
            ("H-bond acceptors", desc.get("NumHAcceptors"), "Hydrogen-bond acceptor count"),
        ]
        for col, (label, value, note) in zip(cols, adme_cards):
            with col:
                st.markdown(metric_card(label, "—" if value is None else str(value), note), unsafe_allow_html=True)

        st.markdown("#### ADME interpretation guide")
        a, b = st.columns(2)
        with a:
            st.markdown('<div class="glass-card"><h4>Absorption & distribution</h4><p>MW, XLogP, TPSA and hydrogen-bond counts can support early physicochemical screening. They do not establish oral bioavailability, plasma protein binding, blood–brain barrier penetration or tissue distribution.</p></div>', unsafe_allow_html=True)
        with b:
            st.markdown('<div class="glass-card"><h4>Metabolism & excretion</h4><p>Metabolic enzymes, clearance, half-life, renal transport and excretion routes require experimental or validated model data. They cannot be reliably derived from SMILES alone.</p></div>', unsafe_allow_html=True)

        st.markdown("#### Source-linked safety evidence")
        st.warning("Toxicity is endpoint-, route-, species- and study-dependent. Do not interpret a missing value as evidence of safety. This dashboard does not calculate human LD50 or recommend doses.")
        if st.button("Retrieve available PubChem safety sections", type="primary"):
            with st.spinner("Checking PubChem record sections…"):
                try:
                    st.session_state.safety_sections = fetch_pubchem_safety_sections(compound["cid"])
                except Exception as exc:
                    st.error(f"Safety section retrieval failed: {exc}")
        sections = st.session_state.safety_sections
        if sections:
            for item in sections:
                with st.expander(item["title"]):
                    st.write(item["summary"])
                    if item.get("url"):
                        st.link_button("Open source record", item["url"])
        else:
            st.caption("No safety sections have been retrieved in this session. Use the button to query the source record.")

        st.markdown("#### Dose information")
        st.info("Age/weight dosing matrices are intentionally not generated from molecular structure. For an approved medicine, dosing must come from its current official product label or a qualified clinician, considering indication, formulation, route, organ function, interactions and patient-specific factors.")

